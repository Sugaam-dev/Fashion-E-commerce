import { COLLECTION_CATEGORIES, CATEGORIES } from "../categories/categories.js";
import { SAREES_PRODUCTS, PAITHANI_SAREES, MAHESHWARI_SAREES, FANCY_SAREES, IKAT_SAREES, ILKAL_SAREES, KOTA_DORIYA_SAREES } from "./sarees.js";
import { DRESS_MATERIAL_PRODUCTS, IKAT_DRESS_MATERIAL, JAMDANI_DRESS_MATERIAL, KOTA_DORIYA_DRESS_MATERIAL, MAHESHWARI_DRESS_MATERIAL, NARAYAN_PETH_DRESS_MATERIAL } from "./dressMaterial.js";
import { READYMADE_PRODUCTS, HALTER_NECK_TOPS, KURTI_WITH_DUPATTA, ONE_PIECE } from "./readymade.js";
import { ACCESSORIES_PRODUCTS, PAITHANI_CLUTCHES, POUCHES, SLING_BAGS } from "./accessories.js";
import { JEWELLERY_PRODUCTS } from "./jewellery.js";

const rawProductsList = [
  ...SAREES_PRODUCTS,
  ...DRESS_MATERIAL_PRODUCTS,
  ...READYMADE_PRODUCTS,
  ...ACCESSORIES_PRODUCTS,
];

function enrichProducts(list) {
  return list.map((item) => {
    let images = item.images && item.images.length > 0 ? [...item.images] : [item.image];
    if (images.length === 1) {
      images.push(images[0]);
    }
    return {
      ...item,
      images,
    };
  });
}

export const PRODUCTS = enrichProducts(rawProductsList);
export { COLLECTION_CATEGORIES, CATEGORIES };
